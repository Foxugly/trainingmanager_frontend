#!/usr/bin/env bash
# =============================================================================
# Training Manager frontend — Fetch runtime config from AWS SSM into an nginx
# snippet.
#
# Run by tm-frontend-runtime-fetch.service (oneshot) at boot, and by the deploy
# pipeline. Reads /tm-frontend/prod/* (eu-west-1) via the EC2 instance role (the
# unit blanks AWS_*_FILE so root's certbot-route53 keys don't shadow the role)
# and writes an nginx snippet `set $tm_* "...";` that the vhost includes and
# injects into index.html.
#
# The frontend config is PUBLIC (served to the browser) → SSM String only, never
# a secret. Guards: reject values with an internal newline, write atomically
# (0644 root), idempotent (no reload if unchanged), validate `nginx -t` first.
# =============================================================================
set -euo pipefail

SSM_PREFIX="${TM_FRONTEND_SSM_PREFIX:-/tm-frontend/prod}"
AWS_REGION="${AWS_REGION:-eu-west-1}"
OUT_FILE="${TM_FRONTEND_RUNTIME_FILE:-/etc/nginx/snippets/tm-frontend-runtime.conf}"

echo "[frontend-runtime] prefix=$SSM_PREFIX region=$AWS_REGION out=$OUT_FILE"

RAW_FILE="$(mktemp)"
TMP_FILE="$(mktemp)"
trap 'rm -f "$RAW_FILE" "$TMP_FILE"' EXIT

# Fetch raw JSON first. If aws errors (IAM/IMDS/network), set -e stops here and
# the previous $OUT_FILE is left untouched.
aws ssm get-parameters-by-path \
    --path "$SSM_PREFIX" \
    --recursive \
    --region "$AWS_REGION" \
    --output json > "$RAW_FILE"

# Parse JSON -> nginx `set` directives. Program from the heredoc (python3 -),
# data from a file argument: no "program vs data on stdin" clash. Missing keys
# fall back to defaults.
python3 - "$SSM_PREFIX" "$TMP_FILE" "$RAW_FILE" <<'PY'
import json, sys
from urllib.parse import urlparse

prefix, out_path, raw_path = sys.argv[1], sys.argv[2], sys.argv[3]
with open(raw_path) as fh:
    params = json.load(fh).get("Parameters", [])

values = {
    "API_BASE_URL": "",
    "VERSION": "",
    "TURNSTILE_SITE_KEY": "",
    "SENTRY_DSN": "",
    "SENTRY_ENV": "production",
    "SENTRY_RELEASE": "",
    "FEATURES": "{}",
}

for p in params:
    key = p["Name"][len(prefix):].lstrip("/")
    value = p["Value"].strip("\r\n")
    if "\n" in value or "\r" in value:
        sys.stderr.write(f"ERROR: value for {key} contains an internal newline; refusing.\n")
        sys.exit(1)
    if key in values:
        values[key] = value

# Every value but FEATURES lands inside a double-quoted nginx `set` AND a
# double-quoted JS string in index.html: a quote, backslash, `$` (nginx variable
# interpolation), `;` or `<`/`>` (could close the <script>) would corrupt the
# page. Refuse them; none occurs in a URL, version, site key, DSN or env name.
FORBIDDEN = set('"$;<>') | {chr(92)}
for key, value in values.items():
    if key != "FEATURES" and FORBIDDEN & set(value):
        sys.stderr.write(f"ERROR: value for {key} contains a forbidden character; refusing.\n")
        sys.exit(1)

# FEATURES must be valid JSON, else fall back to {} (don't break the page). The
# vhost sub_filter injects it WITHOUT quotes (window.__TM_FEATURES=$tm_features
# → literal JS object), but the nginx `set` directive below MUST be quoted (a
# bare {} would be read as an nginx block). nginx strips the quotes when storing
# the variable, so the value stays the raw JSON; escape internal " for nginx.
# It is re-serialized, not passed through as typed: `<`, `>`, `&` and `$` can
# only occur inside JSON strings, where their \uXXXX escapes are equivalent, so a
# value can neither close the inline <script> nor trigger nginx interpolation.
features = values["FEATURES"].strip() or "{}"
try:
    parsed = json.loads(features)
except ValueError:
    sys.stderr.write(f"WARN: FEATURES is not valid JSON ({features!r}); using {{}}.\n")
    parsed = {}
features = json.dumps(parsed, separators=(",", ":"), ensure_ascii=True)
for ch in "<>&$":
    features = features.replace(ch, "\\u%04x" % ord(ch))
features_nginx = features.replace("\\", "\\\\").replace('"', '\\"')

# Derive the Sentry CSP report endpoint from the DSN so the ENFORCED CSP can
# report violations to Sentry. DSN https://<key>@<host>/<project> maps to the
# Security Header endpoint https://<host>/api/<project>/security/?sentry_key=<key>.
# Emitted as the nginx fragment "; report-uri <endpoint>" appended to the CSP
# header; empty (no DSN / malformed) -> the CSP carries no report-uri.
csp_report = ""
dsn = values["SENTRY_DSN"].strip()
if dsn:
    u = urlparse(dsn)
    key = u.username or ""
    host = u.hostname or ""
    port = f":{u.port}" if u.port else ""
    project = u.path.strip("/").split("/")[-1] if u.path else ""
    if key and host and project:
        endpoint = f"{u.scheme}://{host}{port}/api/{project}/security/?sentry_key={key}"
        csp_report = f"; report-uri {endpoint}"

lines = [
    "# AUTO-GENERATED by deploy/fetch-frontend-runtime-from-ssm.sh",
    f"# Source of truth: AWS SSM {prefix}/* . Manual edits are overwritten on the",
    "# next service restart / deploy.",
    f'set $tm_api_base       "{values["API_BASE_URL"]}";',
    f'set $tm_version        "{values["VERSION"]}";',
    f'set $tm_turnstile      "{values["TURNSTILE_SITE_KEY"]}";',
    f'set $tm_sentry_dsn     "{values["SENTRY_DSN"]}";',
    f'set $tm_sentry_env     "{values["SENTRY_ENV"]}";',
    f'set $tm_sentry_release "{values["SENTRY_RELEASE"]}";',
    f'set $tm_features       "{features_nginx}";',
    f'set $tm_csp_report     "{csp_report}";',
]
with open(out_path, "w") as fh:
    fh.write("\n".join(lines) + "\n")
PY

# Idempotence: nothing to do if the snippet is identical (avoids an nginx reload).
if [ -f "$OUT_FILE" ] && cmp -s "$TMP_FILE" "$OUT_FILE"; then
    echo "[frontend-runtime] $OUT_FILE unchanged — no reload needed"
    exit 0
fi

mkdir -p "$(dirname "$OUT_FILE")"
# Keep the previous snippet: if the new one fails `nginx -t`, it is put back, so
# a bad value never stays on disk to break the next nginx reload or restart.
BACKUP_FILE=""
if [ -f "$OUT_FILE" ]; then
    BACKUP_FILE="$(mktemp)"
    cp -p "$OUT_FILE" "$BACKUP_FILE"
fi
install -m 0644 -o root -g root "$TMP_FILE" "$OUT_FILE"

# Validate the full config (vhost + snippet) before reloading. If KO, restore
# the previous snippet and don't reload (nginx keeps the running config).
if ! nginx -t; then
    if [ -n "$BACKUP_FILE" ]; then
        install -m 0644 -o root -g root "$BACKUP_FILE" "$OUT_FILE"
        rm -f "$BACKUP_FILE"
    else
        rm -f "$OUT_FILE"
    fi
    echo "ERROR: nginx -t failed with the new $OUT_FILE — previous snippet restored, no reload" >&2
    exit 3
fi
if [ -n "$BACKUP_FILE" ]; then rm -f "$BACKUP_FILE"; fi
echo "[frontend-runtime] $OUT_FILE updated"

systemctl reload nginx
echo "[frontend-runtime] nginx reloaded"
